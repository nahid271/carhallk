export function getListingById(id: string): Listing | undefined {
  return listings.find((l) => l.id === id || l.slug === id);
}

export function getDealerById(id: string): Dealer | undefined {
  return dealers.find((d) => d.id === id || d.slug === id);
}

export function getListingsByDealer(dealerId: string): Listing[] {
  return listings.filter((l) => l.dealerId === dealerId);
}

export function getFeaturedListings(): Listing[] {
  return listings.filter((l) => l.featured);
}

export function getRelatedListings(listing: Listing): Listing[] {
  return listings
    .filter((l) => l.id !== listing.id && (l.bodyType === listing.bodyType || l.make === listing.make))
    .slice(0, 3);
}
